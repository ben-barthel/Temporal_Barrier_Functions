function reproduce_random_sphere_experiments(T_sim)
%REPRODUCE_RANDOM_SPHERE_EXPERIMENTS  Paper experiments: independent
%   multi-agent pursuit evasion (Table "per-cell statistics", random
%   sphere scenarios).
%
%   reproduce_random_sphere_experiments()        % full T = 50,000 s runs
%   reproduce_random_sphere_experiments(1000)    % shorter sanity runs
%
%   Runs 9 cells = 3 missions x 3 CBF variants:
%     missions:  random_sphere            (8 evaders,  no pursuers)
%                random_sphere_pursuit    (8 evaders + 3 slow pursuers, adv 0.9)
%                random_sphere_pursuit    (8 evaders + 3 fast pursuers, adv 1.5)
%     variants:  none  /  hocbf  /  attc_vraw (iw_huber3 / data1)
%
%   Each cell is saved to ../Results/paper_random_sphere/<tag>__<cbf>.mat
%   with the raw result struct (res) and summary metrics.  At the paper's
%   T = 50,000 s each cell takes several hours — on a cluster, run cells
%   in parallel by splitting the loop.  After all 9 cells finish, run
%   plot_paper_figures.m to generate the figures and summary table.

if nargin < 1 || isempty(T_sim), T_sim = 50000; end

addpath(fullfile(fileparts(mfilename('fullpath')), '..'));
out_dir = fullfile(fileparts(mfilename('fullpath')), '..', '..', ...
                   'Results', 'paper_random_sphere');
if ~exist(out_dir, 'dir'), mkdir(out_dir); end

seed = 42;

missions = {
    struct('name','random_sphere',         'num_agents',8,  'num_pursuers',0, ...
           'pursuit_advantage',1.5, 'tag','random_sphere'), ...
    struct('name','random_sphere_pursuit', 'num_agents',11, 'num_pursuers',3, ...
           'pursuit_advantage',0.9, 'tag','random_sphere_pursuit_adv0p9'), ...
    struct('name','random_sphere_pursuit', 'num_agents',11, 'num_pursuers',3, ...
           'pursuit_advantage',1.5, 'tag','random_sphere_pursuit_adv1p5')};

% CBF hyperparameters (identical to the paper)
hocbf_args = { ...
    'cbf_type', 'hocbf', ...
    'cbf_alpha1',            0.1, ...
    'cbf_activate_dist',     4, ...
    'cbf_activate_dist_adv', 16, ...
    'r_cbf',                 0.5, ...
    'r_cbf_adv',             1};
attc_args = { ...
    'cbf_type', 'attc_vraw', ...
    'attc_loss',             'iw_huber3', ...
    'attc_data_tag',         'data1', ...
    'attc_alpha',            0.1, ...
    'attc_activate_tau',     10, ...
    'attc_activate_tau_adv', 20, ...
    'attc_tau_min',          1, ...
    'attc_tau_min_adv',      5, ...
    'r_cbf',                 1};
none_args = {'cbf_type', 'none', 'r_cbf', 1};

variants = {
    struct('suffix', 'none',                          'args', {none_args});
    struct('suffix', 'hocbf',                         'args', {hocbf_args});
    struct('suffix', 'attc_vraw__iw_huber3__data1',   'args', {attc_args})};

for mi = 1:numel(missions)
    M = missions{mi};
    for vi = 1:numel(variants)
        V = variants{vi};
        out_file = fullfile(out_dir, sprintf('%s__%s.mat', M.tag, V.suffix));
        if exist(out_file, 'file')
            fprintf('[skip] %s already exists\n', out_file);
            continue;
        end

        fprintf('\n================================================\n');
        fprintf('  mission = %s   cbf = %s   T_sim = %d s\n', ...
                M.tag, V.suffix, T_sim);
        fprintf('================================================\n');

        rng(seed);
        t0 = tic;
        args = V.args;
        res = auspice_sim( ...
            'dim',               3, ...
            'mission',           M.name, ...
            'num_agents',        M.num_agents, ...
            'num_pursuers',      M.num_pursuers, ...
            'pursuit_advantage', M.pursuit_advantage, ...
            'r_ttc',             0.1, ...
            'T_sim',             T_sim, ...
            'noise_std_mult',    1, ...
            'use_kalman_filter', false, ...
            'compute_attc',      false, ...
            args{:});
        run_seconds = toc(t0);

        metrics             = sweep_cbf_extract_metrics(res);
        metrics.cbf_type    = V.suffix;
        metrics.run_seconds = run_seconds;

        save(out_file, 'res', 'metrics', '-v7.3');
        fprintf('  saved %s   (%.1f s wall time)\n', out_file, run_seconds);
    end
end

fprintf('\nAll cells complete.  Run plot_paper_figures.m next.\n');
end
